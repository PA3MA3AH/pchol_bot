NFT_COLORS = ["Жёлтый", "Оранжевый", "Красный", "Чёрный", "Синий"]
NFT_SYMBOLS = ["🐝", "🌸", "🦟", "🪰", "☀"]
NFT_BEE_TYPES = ["Оса", "Шмель", "Шершень", "Пчол", "Стрекоза", "Муха"]


def level_multiplier(level: int) -> float:
    return 1.0 + (level - 1) * 0.2 + (level - 1) * 0.05


def generate_nft_pattern(nft_id: int) -> dict:
    idx = nft_id - 1
    color = NFT_COLORS[(idx // (len(NFT_SYMBOLS) * len(NFT_BEE_TYPES))) % len(NFT_COLORS)]
    symbol = NFT_SYMBOLS[(idx // len(NFT_BEE_TYPES)) % len(NFT_SYMBOLS)]
    bee = NFT_BEE_TYPES[idx % len(NFT_BEE_TYPES)]
    return {"color": color, "symbol": symbol, "bee": bee}
